<p class="lead">Movewise es gratis para compradores y vendedores. Los agentes nos pagan por presentaciones, y solo con personas que los eligieron.</p>
<h2>Quién le paga a Movewise</h2>
<p>Agentes y corretajes de bienes raíces. Cuando estés listo para hablar con un agente, te mostramos tres agentes locales. Si eliges uno y tocas Conectar, ese agente le paga a Movewise por la presentación. Algunos corretajes en cambio pagan una parte de su comisión al cerrar, como honorario de referencia entre corredores con licencia, donde el estado lo permite.</p>
<h2>Lo que nunca hacemos</h2>
<ul>
    <li>Nunca vendemos tu información a un montón de agentes. Un agente a la vez, elegido por ti.</li>
    <li>Nunca te contactamos, ni dejamos que un agente te contacte, hasta que eliges un agente y tocas Conectar.</li>
    <li>Ningún prestamista, compañía de títulos ni aseguradora nos paga por referencias, y no te empujamos a los nuestros.</li>
    <li>Los agentes no pueden pagar por mejores reseñas ni para ocultar las malas.</li>
</ul>
<h2>Cómo se eligen los agentes</h2>
<p>Los tres agentes que ves cubren la zona y el precio de la casa, tienen licencia en el estado y pueden recibir clientes nuevos. Se ordenan con reglas publicadas: qué tan rápido responden, cómo los califican sus clientes y sus resultados en la zona, con un turno justo para agentes nuevos. Nunca usamos nada sobre ti excepto la casa, la zona, el precio y el idioma que pediste.</p>
<h2>Quién opera Movewise</h2>
<p>Movewise Homes es operado por RightAlly. En cada estado, un corredor administrador con licencia es el corredor responsable de Movewise: consulta <a href="/es/brokers">Corredores y licencias</a>.</p>
