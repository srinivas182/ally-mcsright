<p class="lead">Movewise is free for buyers and sellers. Agents pay us for introductions, and only to people who chose them.</p>
<h2>Who pays Movewise</h2>
<p>Real estate agents and brokerages. When you're ready to talk to an agent, we show you three local agents. If you choose one and tap Connect, that agent pays Movewise for the introduction. Some brokerages instead pay a share of their commission when you close, as a referral fee between licensed brokers, where the state allows it.</p>
<h2>What we never do</h2>
<ul>
    <li>We never sell your information to a crowd of agents. One agent at a time, chosen by you.</li>
    <li>We never contact you, or let an agent contact you, until you choose an agent and tap Connect.</li>
    <li>No lender, title company or insurer pays us for referrals, and we don't push our own.</li>
    <li>Agents can't pay for better reviews or to hide bad ones.</li>
</ul>
<h2>How agents are chosen</h2>
<p>The three agents you see cover the area and price of the home, are licensed in the state and have room for new clients. They're ranked by published rules: how quickly they reply, how clients rate them and their results nearby, with a fair turn for newer agents. We never use anything about you except the home, the area, the price and the language you asked for.</p>
<h2>Who runs Movewise</h2>
<p>Movewise Homes is run by RightAlly. In each state, a licensed managing broker is the broker of record for Movewise: see <a href="/brokers">Brokers and licences</a>.</p>
