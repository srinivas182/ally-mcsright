<h2>Who sees it</h2>
<p>Only the one agent you choose, and their brokerage, receive your details and your conversation, so they can help you. If you change agent, the new agent sees them only after you choose them. We use service providers (hosting, email, text messages) under contracts that limit them to helping us run Movewise.</p>
<p>We never sell your personal information or share it for advertising, and we never pass it to lenders, title companies or insurers.</p>
<h2>Your choices</h2>
<p>You can pause or stop contact from your agent at any time, see and download what we hold about you, correct it, or delete your account. Texts include STOP to opt out.</p>
<h2>Children</h2>
<p>Movewise isn't for children under 16, and we don't knowingly collect their information.</p>
